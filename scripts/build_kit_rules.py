#!/usr/bin/env python3
"""Write supabase/kit_rules.sql from the KITS list in index.html, so the database knows what unlocks every kit.

The database then works out each account's kits itself (from every day played, every signed-in score and its answers,
streaks, daily wins, Infinity), instead of only trusting what a device sent. Profiles, Socials and every ranking show
the same, correct kits whichever device someone plays on.

Run after adding or changing a kit in index.html, then paste supabase/kit_rules.sql into Supabase -> SQL Editor -> Run,
and run supabase/profile_v2.sql again (it recounts everyone).
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
block = src[src.index('const KITS=['):]
block = block[:block.index('\n];')]

rules = []
for m in re.finditer(r"\{id:'([a-z0-9-]+)'[^\n]*?req:(null|\['([a-z0-9]+)',(\d+)\])", block):
    kid, req, typ, n = m.group(1), m.group(2), m.group(3), m.group(4)
    if req != 'null':
        rules.append((kid, typ, int(n)))

KNOWN = {'games', 'streak', 'scr', 'scr1', 'best', 'allfive', 'big', 'level', 'win', 'crew', 'inf', 'hw', 'hw31', 'hwscr', 'hwhi'}
unknown = sorted({t for _, t, _ in rules} - KNOWN)
if unknown:
    raise SystemExit(f'New kit rule type(s) {unknown}: teach lg_server_kits in this script how to count them first.')

# the same scoring the game uses (index.html: PTS_FROM, PTS_OLD/PTS_NEW, ZONES, BIG_SCORE)
pts_from = re.search(r"PTS_FROM='(\d{4}-\d\d-\d\d)'", src).group(1)
big = int(re.search(r'BIG_SCORE=(\d+)', src).group(1))
zones = [z for z in re.findall(r"\[([\d.]+),['\"]", re.search(r'const ZONES=\[(.*?)\];', src).group(1))]

values = ',\n    '.join(f"('{k}', '{t}', {n})" for k, t, n in rules)
sql = f"""-- Kit rules: what unlocks every kit, and the database working out each account's kits.
-- GENERATED by scripts/build_kit_rules.py from the KITS list in index.html. Don't edit by hand: change the kit there and
-- run the script again.
-- Paste this whole file into Supabase -> SQL Editor -> New query -> Run. Safe to run more than once.
-- Then run supabase/profile_v2.sql again: it recounts everyone, kits included.

create or replace function public.lg_kit_rules()
returns table (id text, t text, n int) language sql immutable as $$
  values
    {values}
$$;

-- every kit an account has earned, from the database's own records
create or replace function public.lg_server_kits(u uuid)
returns text[] language sql stable security definer set search_path = public as $$
  with d as (select day from lg_days_of(u)),
       runs as (select count(*) as c from (select day - (row_number() over (order by day))::int as grp from d) g group by grp),
       s as (select ps.day, ps.score, ps.picks from player_scores ps where ps.user_id = u and not ps.removed),
       -- answers saved with each score: [position, answer, points, question]; points on either scale, read on the new one
       np as (select s.day, (e.value->>2)::int as p,
                     case (e.value->>2)::int when 10 then 10 when 25 then 30 when 30 then 30 when 40 then 60 when 60 then 60
                                             when 70 then 85 when 85 then 85 when 100 then 100 else 0 end as np
                from s, jsonb_array_elements(case when jsonb_typeof(s.picks) = 'array' then s.picks else '[]'::jsonb end) e
               where jsonb_typeof(e.value) = 'array' and (e.value->>2) ~ '^[0-9]+$'),
       ds as (select s.day,
                     coalesce((select sum(np.np) from np where np.day = s.day),
                              case when s.day < date '{pts_from}' then least(500, round(s.score * 1.17)) else s.score end) as sc,
                     (select count(*) from np where np.day = s.day and np.p = 100) as scr,
                     coalesce((select count(*) = 5 and bool_and(np.p > 0) from np where np.day = s.day), false) as five
                from s),
       st as (select
                (select count(*) from d) as games,
                coalesce((select max(c) from runs), 0) as streak,
                coalesce((select max(sc) from ds), 0) as best,
                coalesce((select sum(scr) from ds), 0) as scr,
                coalesce((select max(scr) from ds), 0) as scr1,
                (select count(*) from ds where five) as allfive,
                (select count(*) from ds where sc >= {big}) as big,
                (select count(*) from d where day between date '2026-10-27' and date '2026-11-02') as hw,
                (select count(*) from d where day = date '2026-10-31') as hw31,
                coalesce((select sum(scr) from ds where day between date '2026-10-27' and date '2026-11-02'), 0) as hwscr,
                coalesce((select max(sc) from ds where day between date '2026-10-27' and date '2026-11-02'), 0) as hwhi,
                lg_wins(u) as win,
                case when lg_is_crew(u) then 1 else 0 end as crew,
                case when exists (select 1 from infinity_subs i where i.user_id = u
                                    and i.status in ('active', 'trialing', 'on_trial', 'past_due', 'cancelled', 'paid')) then 1 else 0 end as inf)
  select coalesce(array_agg(r.id order by r.id), '{{}}')
    from lg_kit_rules() r, st
   where case r.t
           when 'games' then st.games when 'streak' then st.streak when 'scr' then st.scr when 'scr1' then st.scr1
           when 'best' then st.best when 'allfive' then st.allfive when 'big' then st.big
           when 'level' then (select count(*) - 1 from unnest(array[{', '.join(zones)}]::numeric[]) z where st.best / 500.0 >= z)
           when 'win' then st.win when 'crew' then st.crew when 'inf' then st.inf
           when 'hw' then st.hw when 'hw31' then st.hw31 when 'hwscr' then st.hwscr when 'hwhi' then st.hwhi
         end >= r.n
$$;
revoke all on function public.lg_kit_rules(), public.lg_server_kits(uuid) from public, anon, authenticated;
"""
open(os.path.join(ROOT, 'supabase', 'kit_rules.sql'), 'w', encoding='utf-8').write(sql)
print(f'{len(rules)} kit rules written to supabase/kit_rules.sql')
